"""Collision samples of the arm links 1-4 (upper arm, forearm, wrist with camera) into config/arm_links_geometry.json.

The course meshes in data/sim/dofbot_arm.blend are in their own link frames (the URDF chain below), so the
voxelized vertices can be placed with forward kinematics. link5 (the gripper) is extracted separately with
its four-bar (scripts/blender_extract_gripper.py -> config/gripper_geometry.json).

    /Applications/Blender.app/Contents/MacOS/Blender -b data/sim/dofbot_arm.blend \
        -P scripts/blender_extract_links.py -- [--voxel 0.006] [--out config/arm_links_geometry.json]
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

import bpy
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
LINKS = ("link1", "link2", "link3", "link4")


def voxel(points: np.ndarray, size: float) -> np.ndarray:
    """One point per occupied voxel: the mean of the vertices in it (surface samples, not a solid)."""
    keys = np.floor(points / size).astype(np.int64)
    _, inv = np.unique(keys, axis=0, return_inverse=True)
    inv = inv.reshape(-1)
    out = np.zeros((inv.max() + 1, 3))
    np.add.at(out, inv, points)
    return out / np.bincount(inv)[:, None]


def main() -> int:
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--voxel", type=float, default=0.006)
    ap.add_argument("--out", default=str(ROOT / "config" / "arm_links_geometry.json"))
    a = ap.parse_args(argv)
    out = {"_status": f"{date.today().isoformat()}. Generated by scripts/blender_extract_links.py from "
                      "data/sim/dofbot_arm.blend (course URDF meshes); do not edit by hand.",
           "frame_note": "points in each link's own URDF frame (dofbot_kinematics chain, servo angle - 90 about z)",
           "voxel_m": a.voxel, "points_m": {}, "extent_m": {}}
    for n in LINKS:
        obj = bpy.data.objects[f"dofbot_{n}"]
        v = np.array([p.co[:] for p in obj.data.vertices])
        pts = voxel(v, a.voxel)
        out["points_m"][n] = [[round(float(c), 5) for c in p] for p in pts]
        out["extent_m"][n] = [[round(float(c), 4) for c in v.min(0)], [round(float(c), 4) for c in v.max(0)]]
        print(f"{n}: {len(v)} vertices -> {len(pts)} samples, extent {out['extent_m'][n]}")
    Path(a.out).write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
