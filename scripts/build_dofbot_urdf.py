#!/usr/bin/env python3
"""Build a complete DOFBOT URDF (5 arm joints + gripper) from the archived upstream model.

The upstream `dofbot.urdf` has five revolute joints and no gripper: its IK pushes a hard-coded
0.12 m "gripper length" out of link5.  This script keeps that arm chain untouched (same joint
origins/limits, so existing calibration still applies) and adds:

  gripper_joint_left / gripper_joint_right   two prismatic joints along +/-x, mimic-coupled
  grasp_centre, fingertip                    fixed frame markers at the pad centre and the tip

The real jaw is a parallelogram four-bar driven by servo 6; a prismatic pair reproduces its
observable effect (the pads stay parallel and translate apart) and is what Gazebo/MoveIt/RViz
can consume.  The nonlinear servo-6 angle -> gap mapping lives in config/gripper_model.json and
`src/spatial/gripper_model.py`, not in URDF.

    python3 scripts/build_dofbot_urdf.py
    python3 scripts/build_dofbot_urdf.py --j5 0.0655   # USD value instead of the URDF 0.07385

Writes config/urdf/dofbot_with_gripper.urdf.  Meshes are referenced through --mesh-root
(default: the STL folder in 资料/, which is local-only and not in git); pass --no-meshes to
emit primitive-only links.
"""
from __future__ import annotations

import argparse
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "资料" / "官方资料" / "Atlas-200I-DK-A2-机械臂" / "ros2_robot_arm-upstream" / \
    "ros2_ws" / "src" / "dofbot_moveit" / "urdf" / "dofbot.urdf"
STL_DIR = ROOT / "资料" / "展开资源" / "三维结构文件" / "三维结构文件"
MODEL_JSON = ROOT / "config" / "gripper_model.json"
OUT = ROOT / "config" / "urdf" / "dofbot_with_gripper.urdf"

LINK_MESHES = {"base_link": "base_link.STL", "link1": "link1.STL", "link2": "link2.STL",
               "link3": "link3.STL", "link4": "link4.STL", "link5": "link5.STL"}


def fmt(values) -> str:
    return " ".join(f"{v:.6g}" for v in values)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--j5", type=float, default=None,
                        help="override the J4->J5 link length in metres (URDF 0.07385, Isaac USD 0.0655)")
    parser.add_argument("--mesh-root", default=None, help="directory holding the six .STL files")
    parser.add_argument("--no-meshes", action="store_true", help="use primitive boxes instead of STL meshes")
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args()

    model = json.loads(MODEL_JSON.read_text(encoding="utf-8"))
    pad = model["geometry"]["pad"]
    tcp = model["tcp"]
    grip_z = pad["z_range_from_j5_m"][0]
    pad_z1 = pad["z_range_from_j5_m"][1]
    pad_len = pad_z1 - grip_z
    pad_centre = (grip_z + pad_z1) / 2.0
    half_max = model["jaw"]["max_gap_m"] / 2.0

    tree = ET.parse(UPSTREAM)
    robot = tree.getroot()

    if args.j5 is not None:
        for joint in robot.findall("joint"):
            if joint.get("name") == "joint5":
                origin = joint.find("origin")
                xyz = [float(v) for v in origin.get("xyz").split()]
                xyz[0] = -args.j5
                origin.set("xyz", fmt(xyz))

    # keep provenance visible in the file itself
    comment = ET.Comment(
        " Generated by scripts/build_dofbot_urdf.py from the archived upstream dofbot.urdf plus "
        "config/gripper_model.json. Arm chain untouched; gripper = two mimic prismatic pads. "
        f"grasp_centre at z={pad_centre:.4f} m, fingertip at z={tcp['fingertip_m']:.5f} m. ")
    robot.insert(0, comment)

    mesh_root = Path(args.mesh_root) if args.mesh_root else STL_DIR
    if not args.no_meshes:
        for link in robot.findall("link"):
            name = link.get("name")
            if name not in LINK_MESHES:
                continue
            for mesh in link.iter("mesh"):
                try:
                    rel = Path(mesh.get("filename")).name
                except AttributeError:
                    continue
                mesh.set("filename", str((mesh_root / rel).resolve()))

    # ---- gripper pads -------------------------------------------------------------------
    thickness = pad["thickness_m"]
    width = pad["width_m"]
    for side, sign in (("left", -1.0), ("right", +1.0)):
        link = ET.SubElement(robot, "link", {"name": f"gripper_{side}_finger"})
        visual = ET.SubElement(link, "visual")
        ET.SubElement(visual, "origin", {"xyz": fmt([sign * thickness / 2.0, 0.0, 0.0]), "rpy": "0 0 0"})
        geom = ET.SubElement(visual, "geometry")
        ET.SubElement(geom, "box", {"size": fmt([thickness, width, pad_len])})
        ET.SubElement(visual, "material", {"name": f"gripper_{side}"}).append(
            ET.Element("color", {"rgba": "0.2 0.2 0.2 1"}))
        collision = ET.SubElement(link, "collision")
        ET.SubElement(collision, "origin", {"xyz": fmt([sign * thickness / 2.0, 0.0, 0.0]), "rpy": "0 0 0"})
        cgeom = ET.SubElement(collision, "geometry")
        ET.SubElement(cgeom, "box", {"size": fmt([thickness, width, pad_len])})
        # the pads have no meaningful inertia for this project; a 20 g point mass keeps parsers happy
        inertial = ET.SubElement(link, "inertial")
        ET.SubElement(inertial, "mass", {"value": "0.02"})
        ET.SubElement(inertial, "inertia", {"ixx": "1e-6", "ixy": "0", "ixz": "0",
                                            "iyy": "1e-6", "iyz": "0", "izz": "1e-6"})

    for side in ("left", "right"):
        joint = ET.SubElement(robot, "joint", {"name": f"gripper_joint_{side}", "type": "prismatic"})
        ET.SubElement(joint, "origin", {"xyz": fmt([0.0, 0.0, pad_centre]), "rpy": "0 0 0"})
        ET.SubElement(joint, "parent", {"link": "link5"})
        ET.SubElement(joint, "child", {"link": f"gripper_{side}_finger"})
        ET.SubElement(joint, "axis", {"xyz": "1 0 0" if side == "right" else "-1 0 0"})
        ET.SubElement(joint, "limit", {"lower": "0", "upper": fmt([half_max]),
                                       "effort": "10", "velocity": "0.1"})
        if side == "right":
            ET.SubElement(joint, "mimic", {"joint": "gripper_joint_left", "multiplier": "1", "offset": "0"})

    # ---- marker frames used by the planner / MoveIt --------------------------------------
    for name, z in (("grasp_centre", pad_centre), ("fingertip", tcp["fingertip_m"])):
        link = ET.SubElement(robot, "link", {"name": name})
        joint = ET.SubElement(robot, "joint", {"name": f"link5_to_{name}", "type": "fixed"})
        ET.SubElement(joint, "origin", {"xyz": fmt([0.0, 0.0, z]), "rpy": "0 0 0"})
        ET.SubElement(joint, "parent", {"link": "link5"})
        ET.SubElement(joint, "child", {"link": name})

    ET.indent(tree, space="    ")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tree.write(out, encoding="utf-8", xml_declaration=True)

    # ---- report --------------------------------------------------------------------------
    joints = [j.get("name") for j in robot.findall("joint")]
    comments = {
        "file": str(out.relative_to(ROOT)),
        "links": len(robot.findall("link")),
        "joints": len(joints),
        "joint_names": joints,
        "grasp_centre_m": round(pad_centre, 4),
        "finger_stroke_m": round(half_max, 4),
        "mesh_root": None if args.no_meshes else str(mesh_root),
        "j5_origin_x": next(j.find("origin").get("xyz") for j in robot.findall("joint")
                            if j.get("name") == "joint5"),
    }
    print(json.dumps(comments, ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
